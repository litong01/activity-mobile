/**
 * Creates android/local.properties with sdk.dir so Gradle can find the Android SDK.
 * Run after `expo prebuild --platform android` (e.g. npm run prebuild:clean).
 *
 * Uses ANDROID_HOME or ANDROID_SDK_ROOT, or default Mac path.
 */
const fs = require("fs");
const path = require("path");

const androidDir = path.join(__dirname, "..", "android");
const localPropertiesPath = path.join(androidDir, "local.properties");

const sdkPath =
  process.env.ANDROID_HOME ||
  process.env.ANDROID_SDK_ROOT ||
  (process.platform === "darwin"
    ? path.join(process.env.HOME || "", "Library", "Android", "sdk")
    : null);

if (!fs.existsSync(androidDir)) {
  console.log(
    "scripts/setup-android-sdk.js: android/ not found. Run 'npx expo prebuild --platform android' first."
  );
  process.exit(0);
}

if (!sdkPath || !fs.existsSync(sdkPath)) {
  console.error(
    "scripts/setup-android-sdk.js: Android SDK not found. Set ANDROID_HOME (e.g. export ANDROID_HOME=$HOME/Library/Android/sdk) or install Android Studio."
  );
  process.exit(1);
}

const content = `# Auto-generated by scripts/setup-android-sdk.js - do not commit if android/ is gitignored
sdk.dir=${sdkPath.replace(/\\/g, "/")}
`;
fs.writeFileSync(localPropertiesPath, content, "utf8");
console.log("scripts/setup-android-sdk.js: wrote android/local.properties with sdk.dir=" + sdkPath);
